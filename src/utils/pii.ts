// 입력 개인정보 감지. 주민등록번호·외국인등록번호(앞 6자리-뒤 7자리) 또는 13자리 연속 숫자가 들어 있으면 보내지 않는다.
// AI 비용 없이 정규식만. 전화번호·금액(6자리 이하, 쉼표 포함)은 걸리지 않는다.
// 후방 탐색 (?<!…) 은 iOS 16.3 이하 사파리가 파싱 단계에서 SyntaxError 를 내 앱 전체가 안 뜨므로 쓰지 않는다.
const PII_RE = /\d{6}\s*-\s*[1-8]\d{6}|(?:^|\D)\d{13}(?!\d)/;

export const hasPii = (text: string) => PII_RE.test(text);
